import AppKit

final class ClipboardMonitor {
    var onCopy: ((String) -> Void)?
    var onCopyImage: ((Data) -> Void)?
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    func start() {
        let t = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after Clippo itself writes to the pasteboard so its own writes aren't recorded as copies.
    func ignoreCurrentChange() {
        lastChange = NSPasteboard.general.changeCount
    }

    /// Markers password managers put on secrets (nspasteboard.org convention + vendor-specific ones).
    private static let secretTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.apple.Passwords"),
        .init("com.bitwarden.desktop"),
    ]

    /// Bundle ids whose copies are never recorded (password tools by default; users add banks etc.).
    static let defaultExcluded = ["com.apple.keychainaccess", "com.apple.Passwords"]

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if let types = pb.types, !Self.secretTypes.isDisjoint(with: types) { NSLog("Clippo: skipped secret copy"); return }
        if let id = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, Settings.shared.excluded.contains(id) { NSLog("Clippo: skipped copy from excluded %@", id); return }
        if let text = pb.string(forType: .string) {
            if !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { onCopy?(text) }
        } else if let png = ImageStore.png(from: pb) {
            onCopyImage?(png)
        }
    }
}
